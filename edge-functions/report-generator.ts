const BASE_URL = Deno.env.get("INSFORGE_URL") ?? "";
const ANON_KEY = Deno.env.get("INSFORGE_ANON_KEY") ?? "";
const SECRET_KEY = Deno.env.get("INSFORGE_SECRET_KEY") ?? "";

const authHeader = SECRET_KEY ? `Bearer ${SECRET_KEY}` : `Bearer ${ANON_KEY}`;

async function dbFrom(table: string, query: string) {
  const res = await fetch(`${BASE_URL}/database/rest/v1/${table}?${query}`, {
    headers: { Authorization: authHeader, apikey: ANON_KEY, Accept: "application/json" },
  });
  if (!res.ok) return [];
  return res.json();
}

async function dbInsert(table: string, row: Record<string, unknown>) {
  const res = await fetch(`${BASE_URL}/database/rest/v1/${table}`, {
    method: "POST",
    headers: {
      Authorization: authHeader,
      apikey: ANON_KEY,
      "Content-Type": "application/json",
      Prefer: "return=representation",
    },
    body: JSON.stringify(row),
  });
  if (!res.ok) return null;
  const data = await res.json();
  return Array.isArray(data) ? data[0] : data;
}

type Zone = { name: string; state: string; status: string };
type Outage = { cause: string; severity: string; started_at: string; resolved_at: string | null };
type FraudAlert = { alert_type: string; confidence_score: number; status: string };
type Reading = { reading_value: number };

function buildReport(type: string, zones: Zone[], outages: Outage[], fraudAlerts: FraudAlert[], readings: Reading[]): string {
  const active = zones.filter((z) => z.status === "active").length;
  const totalKwh = readings.reduce((s, r) => s + r.reading_value, 0);
  const resolved = outages.filter((o) => o.resolved_at !== null).length;
  const critical = outages.filter((o) => o.severity === "critical").length;
  const openFraud = fraudAlerts.filter((f) => f.status === "open").length;
  const confirmedFraud = fraudAlerts.filter((f) => f.status === "confirmed_fraud").length;
  const highConf = fraudAlerts.filter((f) => f.confidence_score >= 0.8).length;
  const reliability = zones.length > 0 ? ((active / zones.length) * 100).toFixed(1) : "0";
  const period = type === "monthly" ? "Last 30 days" : "Last 7 days";
  const label = type === "monthly" ? "MONTHLY" : "WEEKLY";

  return `SMARTGRID AI — ${label} NETWORK REPORT
Generated: ${new Date().toLocaleString("en-NG")}
Period: ${period}

═══════════════════════════════════════

NETWORK OVERVIEW
  Total Zones:         ${zones.length}
  Active Zones:        ${active}
  Grid Reliability:    ${reliability}%
  Total kWh Metered:   ${totalKwh.toFixed(1)} kWh

OUTAGE SUMMARY
  Total Outages:       ${outages.length}
  Resolved:            ${resolved}
  Critical:            ${critical}

FRAUD DETECTION
  Total Alerts:        ${fraudAlerts.length}
  High Confidence:     ${highConf} (≥80%)
  Confirmed Fraud:     ${confirmedFraud}
  Open Investigations: ${openFraud}

RECOMMENDATIONS
  1. Prioritise restoration in high-severity outage zones
  2. Follow up on ${openFraud} open fraud investigations
  3. Review ${highConf} high-confidence fraud alerts

═══════════════════════════════════════
Report generated by SmartGrid AI · Keotera
`;
}

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
  "Access-Control-Allow-Headers": "Content-Type, Authorization",
};

export default async function handler(req: Request): Promise<Response> {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });
  if (req.method !== "POST") {
    return new Response(JSON.stringify({ error: "Method not allowed" }), { status: 405, headers: { "Content-Type": "application/json" } });
  }

  try {
    const body = await req.json().catch(() => ({}));
    const reportType: string = body.report_type ?? "weekly";
    const title: string = body.title ?? `${reportType.charAt(0).toUpperCase() + reportType.slice(1)} Network Report`;

    const [zones, outages, fraudAlerts, readings] = await Promise.all([
      dbFrom("zones", "select=name,state,status"),
      dbFrom("outages", "select=cause,severity,started_at,resolved_at&order=started_at.desc&limit=100"),
      dbFrom("fraud_alerts", "select=alert_type,confidence_score,status&order=created_at.desc&limit=100"),
      dbFrom("meter_readings", "select=reading_value&order=read_at.desc&limit=500"),
    ]);

    const content = buildReport(reportType, zones as Zone[], outages as Outage[], fraudAlerts as FraudAlert[], readings as Reading[]);

    const saved = await dbInsert("reports", {
      title,
      report_type: reportType,
      content,
      generated_at: new Date().toISOString(),
    });

    return new Response(
      JSON.stringify({ success: true, report: saved ?? { title, report_type: reportType, content } }),
      { headers: { "Content-Type": "application/json", ...corsHeaders } },
    );
  } catch (err) {
    return new Response(
      JSON.stringify({ success: false, error: String(err) }),
      { status: 500, headers: { "Content-Type": "application/json", ...corsHeaders } },
    );
  }
}
