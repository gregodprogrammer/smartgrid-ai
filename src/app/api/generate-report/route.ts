import { NextRequest, NextResponse } from 'next/server'
import { getDb } from '@/lib/db'

const baseUrl = process.env.NEXT_PUBLIC_INSFORGE_URL!
const secretKey = process.env.INSFORGE_SECRET_KEY!
const anonKey = process.env.NEXT_PUBLIC_INSFORGE_ANON_KEY!

export async function POST(req: NextRequest) {
  try {
    const { report_type, zone_id, period_start, period_end } = await req.json()

    if (!report_type || !period_start || !period_end) {
      return NextResponse.json({ error: 'report_type, period_start, and period_end are required' }, { status: 400 })
    }

    const db = getDb()

    // Gather data using PostgREST queries
    const [outagesRes, fraudRes, zonesRes] = await Promise.allSettled([
      (zone_id
        ? db.database.from('outages').select('*', { count: 'exact', head: true })
            .gte('started_at', period_start).lte('started_at', period_end).eq('zone_id', zone_id)
        : db.database.from('outages').select('*', { count: 'exact', head: true })
            .gte('started_at', period_start).lte('started_at', period_end)),
      (zone_id
        ? db.database.from('fraud_alerts').select('*', { count: 'exact', head: true })
            .gte('created_at', period_start).lte('created_at', period_end)
        : db.database.from('fraud_alerts').select('*', { count: 'exact', head: true })
            .gte('created_at', period_start).lte('created_at', period_end)),
      (zone_id
        ? db.database.from('zones').select('name, state, status').eq('id', zone_id).single()
        : db.database.from('zones').select('*', { count: 'exact', head: true })),
    ])

    const outageCount = outagesRes.status === 'fulfilled' ? (outagesRes.value.count ?? 0) : 0
    const fraudCount = fraudRes.status === 'fulfilled' ? (fraudRes.value.count ?? 0) : 0

    let zoneName = 'All Zones'
    if (zone_id && zonesRes.status === 'fulfilled') {
      const z = (zonesRes.value as any).data
      if (z) zoneName = `${z.name} (${z.state})`
    }

    // Confirmed fraud count
    const { count: confirmedFraud } = await db.database
      .from('fraud_alerts')
      .select('*', { count: 'exact', head: true })
      .eq('status', 'confirmed_fraud')
      .gte('created_at', period_start)
      .lte('created_at', period_end)

    const summary = {
      outages: { total: outageCount },
      fraud: { total: fraudCount, confirmed: confirmedFraud ?? 0 },
      zone: zoneName,
      period: { start: period_start, end: period_end },
    }

    const typeLabelMap: Record<string, string> = { weekly: 'Weekly', monthly: 'Monthly', incident: 'Incident', fraud: 'Fraud Analysis' }
    const typeLabel = typeLabelMap[report_type] || report_type
    const prompt = `Generate a professional operational report for AEDC — SmartGrid AI Platform.
Report by Keotera.

Report Type: ${typeLabel}
Period: ${period_start} to ${period_end}
Zone: ${zoneName}

Data:
${JSON.stringify(summary, null, 2)}

Format with these sections:
1. Executive Summary (3-4 sentences)
2. Outage Statistics (table format)
3. Zone Performance Rankings
4. Fraud Detection Summary
5. Customer Impact Assessment
6. Operational Recommendations (bullet points)
7. Conclusion

Use professional language suitable for AEDC utility executives and European development finance evaluators (AFD, EU). Include specific numbers and percentages. Highlight improvements and areas needing attention.`

    let reportContent = ''

    try {
      const aiRes = await fetch(`${baseUrl}/api/ai/chat`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${secretKey || anonKey}`,
        },
        body: JSON.stringify({
          model: 'gpt-4o-mini',
          messages: [
            { role: 'system', content: 'You are SmartGrid Report Generator — a professional energy sector report writer for Nigerian distribution companies and European grant evaluators.' },
            { role: 'user', content: prompt },
          ],
        }),
      })

      if (aiRes.ok) {
        const aiData = await aiRes.json()
        reportContent = aiData.choices?.[0]?.message?.content || aiData.response || ''
      }
    } catch {
      // Fallback below
    }

    if (!reportContent) {
      reportContent = `SMARTGRID AI — ${typeLabel.toUpperCase()} REPORT
Generated by Keotera SmartGrid AI Platform
========================================

Zone: ${zoneName}
Period: ${period_start} to ${period_end}
Generated: ${new Date().toLocaleString('en-NG')}

1. EXECUTIVE SUMMARY
--------------------
This ${typeLabel.toLowerCase()} report covers SmartGrid AI operations for ${zoneName}. The network recorded ${summary.outages.total} outage events and ${summary.fraud.total} fraud alerts during this period. The AI-powered monitoring system continues to provide real-time visibility across Nigeria's distribution network.

2. KEY METRICS
--------------
• Total Outages: ${summary.outages.total}
• Fraud Alerts: ${summary.fraud.total}
• Confirmed Fraud Cases: ${summary.fraud.confirmed}
• Estimated Revenue at Risk: ₦${(summary.fraud.confirmed * 85000).toLocaleString()}

3. ZONE PERFORMANCE ANALYSIS
-----------------------------
The distribution network operated within acceptable parameters during the report period. Zones with active outages have been flagged for priority restoration.

4. FRAUD DETECTION SUMMARY
---------------------------
${summary.fraud.total > 0 ? `${summary.fraud.total} fraud alerts were flagged by the AI detection engine, with ${summary.fraud.confirmed} confirmed cases.` : 'No fraud alerts triggered during this period.'}

5. RECOMMENDATIONS
------------------
• Deploy field teams to investigate all open outage zones
• Follow up on ${summary.fraud.confirmed} confirmed fraud cases
• Schedule preventive maintenance for zones with high outage frequency

---
Report generated by SmartGrid AI | Powered by Keotera
For Nigeria's electricity distribution sector`
    }

    const title = `${typeLabel} Report — ${zoneName} — ${new Date(period_start).toLocaleDateString('en-NG', { month: 'short', year: 'numeric' })}`

    const { data: savedReport } = await db.database
      .from('reports')
      .insert({
        title,
        report_type,
        zone_id: zone_id || null,
        content: reportContent,
        generated_by: 'SmartGrid AI',
      })
      .select()
      .single()

    const report = savedReport ?? {
      id: `r-${Date.now()}`,
      title,
      report_type,
      zone_id: zone_id || null,
      content: reportContent,
      created_at: new Date().toISOString(),
    }

    return NextResponse.json({ report })
  } catch (error) {
    console.error('Report generation error:', error)
    return NextResponse.json({ error: 'Failed to generate report' }, { status: 500 })
  }
}
